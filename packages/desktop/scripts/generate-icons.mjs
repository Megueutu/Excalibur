// Regenerates src/renderer/shared/ui/solar-icons.ts from @iconify-json/solar.
// Edit the ICONS map, then run: npm run icons
import { createRequire } from 'node:module'
import { writeFileSync } from 'node:fs'

const require = createRequire(import.meta.url)
const solar = require('@iconify-json/solar/icons.json')

const ICONS = {
  ArrowLeft: 'arrow-left-linear',
  ArrowRight: 'arrow-right-linear',
  Check: 'check-linear',
  ChevronDown: 'alt-arrow-down-linear',
  ChevronRight: 'alt-arrow-right-linear',
  FileText: 'document-text-linear',
  Folder: 'folder-linear',
  GitBranch: 'git-branch-linear',
  House: 'home-2-linear',
  Network: 'structure-linear',
  Plus: 'add-linear',
  RefreshCw: 'refresh-linear',
  Search: 'magnifer-linear',
  Settings: 'settings-linear',
  Sparkles: 'stars-linear',
  TriangleAlert: 'danger-triangle-linear',
  User: 'user-rounded-linear',
  X: 'close-linear',
}

const lines = Object.entries(ICONS).map(([component, name]) => {
  const icon = solar.icons[name] ?? solar.icons[solar.aliases?.[name]?.parent]
  if (!icon) throw new Error(`Solar has no icon "${name}"`)
  return `  ${component}: ${JSON.stringify(icon.body)},`
})

writeFileSync(
  new URL('../src/renderer/shared/ui/solar-icons.ts', import.meta.url),
  `// Generated by scripts/generate-icons.mjs. Do not edit.\n// Solar icon set by 480 Design, CC BY 4.0: https://github.com/480-Design/Solar-Icon-Set\nexport const SOLAR_BODIES = {\n${lines.join('\n')}\n} as const\n`,
)
console.log(`wrote ${lines.length} icons`)

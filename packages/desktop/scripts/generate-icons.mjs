// Regenerates the icon data from the two icon sets the app uses:
//   - Solar Linear (@iconify-json/solar, CC BY 4.0): the interface icons, drawn at stroke width 2.
//   - Simple Icons (simple-icons, CC0): git, GitHub and the stack brands, single color.
// Edit ICONS or BRANDS, then run: npm run icons
import { createRequire } from 'node:module'
import { writeFileSync } from 'node:fs'
import * as simple from 'simple-icons'

const require = createRequire(import.meta.url)
const solar = require('@iconify-json/solar/icons.json')

const ICONS = {
  AddFolder: 'add-folder-linear',
  Import: 'import-linear',
  Tune: 'tuning-2-linear',
  Info: 'info-circle-linear',
  ArrowLeft: 'arrow-left-linear',
  ArrowRight: 'arrow-right-linear',
  Check: 'check-linear',
  ChevronDown: 'alt-arrow-down-linear',
  ChevronRight: 'alt-arrow-right-linear',
  FileText: 'document-text-linear',
  Folder: 'folder-linear',
  GitBranch: 'git-branch-linear',
  House: 'home-2-linear',
  Network: 'structure-linear',
  Plus: 'add-linear',
  RefreshCw: 'refresh-linear',
  Search: 'magnifer-linear',
  Settings: 'settings-linear',
  Sparkles: 'stars-linear',
  TriangleAlert: 'danger-triangle-linear',
  User: 'user-rounded-linear',
  X: 'close-linear',
}

const lines = Object.entries(ICONS).map(([component, name]) => {
  const icon = solar.icons[name] ?? solar.icons[solar.aliases?.[name]?.parent]
  if (!icon) throw new Error(`Solar has no icon "${name}"`)
  // Solar draws at 1.5; 2 reads sturdier at 16px and keeps every line icon the same weight.
  return `  ${component}: ${JSON.stringify(icon.body.replaceAll('stroke-width="1.5"', 'stroke-width="2"'))},`
})

writeFileSync(
  new URL('../src/renderer/shared/ui/solar-icons.ts', import.meta.url),
  `// Generated by scripts/generate-icons.mjs. Do not edit.\n// Solar icon set by 480 Design, CC BY 4.0: https://github.com/480-Design/Solar-Icon-Set\nexport const SOLAR_BODIES = {\n${lines.join('\n')}\n} as const\n`,
)
console.log(`wrote ${lines.length} icons`)

// Brands: key is the Simple Icons slug the stack detectors map to.
const BRANDS = [
  'git', 'github', 'typescript', 'javascript', 'python', 'react', 'vite', 'tailwindcss', 'electron',
  'nodedotjs', 'kotlin', 'nestjs', 'docker', 'markdown', 'gnubash', 'css', 'html5', 'openjdk', 'spring',
  'go', 'rust', 'php', 'vuedotjs', 'angular', 'nextdotjs', 'swift', 'flutter', 'dart', 'ruby', 'svelte',
]
const brandLines = BRANDS.map((slug) => {
  const key = 'si' + slug[0].toUpperCase() + slug.slice(1)
  const icon = simple[key]
  if (!icon) throw new Error(`Simple Icons has no "${slug}"`)
  return `  ${slug}: { title: ${JSON.stringify(icon.title)}, path: ${JSON.stringify(icon.path)} },`
})
const brandFile = [
  '// Generated by scripts/generate-icons.mjs. Do not edit.',
  '// Simple Icons, CC0: https://simpleicons.org',
  'export const BRANDS: Record<string, { title: string; path: string }> = {',
  ...brandLines,
  '}',
  '',
].join('\n')
writeFileSync(new URL('../src/renderer/shared/ui/brand-icons.ts', import.meta.url), brandFile)
console.log(`wrote ${brandLines.length} brands`)

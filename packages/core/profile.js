import fs from 'node:fs'
import path from 'node:path'
import crypto from 'node:crypto'
import { execFileSync } from 'node:child_process'
import { parse } from './yaml.js'
import { projectPaths, packageRoot, CONTEXT_DIR } from './paths.js'
import { listFiles, copyDir, ensureDir, isEmptyDir, ensureGitignore, removeGitignoreEntries } from './fsx.js'
import { getProfileRepo, getProjectSettings, touchProject } from './user.js'

/**
 * The user profile: a repository of the user's own standing instructions for AI agents,
 * valid across every project. Its shape:
 *
 *   global/<file>.md              applies everywhere
 *   profiles/<name>/<file>.md     applies only to projects that use <name>
 *
 * Each file may open with frontmatter holding `description` and `when`. `when: always`
 * (the default) means the file is read in full at the start of a session; any other
 * text is a trigger, and the agent opens the file only when it applies.
 *
 * A project does not read the repository directly, because isolated agents, cloud
 * sessions and teammates cannot see it. `syncUserProfile` copies a snapshot into the
 * project instead:
 *
 *   <custom_dir>/context/user-profile.md    index + the `always` files, read every session
 *   <custom_dir>/user-profile/<file>.md     every selected file, opened on demand
 */

export const PROFILE_TEMPLATE_DIR = path.join(packageRoot, 'lib', 'onboarding', 'profile-template')
export const SNAPSHOT_FILE = 'user-profile.md'
export const SNAPSHOT_DIR = 'user-profile'

const FRONTMATTER = /^---\r?\n([\s\S]*?)\r?\n---\r?\n?/

export function parseFrontmatter(text) {
  const match = text.match(FRONTMATTER)
  if (!match) return { data: {}, body: text, has: false }
  let data = {}
  try {
    data = parse(match[1]) ?? {}
  } catch {
    data = {}
  }
  return { data: typeof data === 'object' && !Array.isArray(data) ? data : {}, body: text.slice(match[0].length), has: true }
}

function readEntry(repo, rel, scope) {
  const raw = fs.readFileSync(path.join(repo, rel), 'utf8')
  const { data, body, has } = parseFrontmatter(raw)
  const when = typeof data.when === 'string' && data.when.trim() ? data.when.trim() : 'always'
  return {
    rel,
    scope,
    raw,
    body: body.trim(),
    description: typeof data.description === 'string' ? data.description.trim() : '',
    when,
    always: when.toLowerCase() === 'always',
    hasFrontmatter: has,
    hasWhen: typeof data.when === 'string' && data.when.trim() !== '',
  }
}

/** Names of the optional profiles in the repository (`profiles/<name>/`). */
export function listProfiles(repo) {
  const dir = path.join(repo, 'profiles')
  if (!fs.existsSync(dir)) return []
  return fs.readdirSync(dir, { withFileTypes: true })
    .filter((e) => e.isDirectory() && !e.name.startsWith('.'))
    .map((e) => e.name)
    .sort()
}

/** Every instruction file in the repository, with what is wrong with each. */
export function scanProfile(repo) {
  const files = []
  for (const f of listFiles(path.join(repo, 'global')).filter((x) => x.endsWith('.md')).sort()) {
    files.push(readEntry(repo, `global/${f}`, 'global'))
  }
  for (const name of listProfiles(repo)) {
    for (const f of listFiles(path.join(repo, 'profiles', name)).filter((x) => x.endsWith('.md')).sort()) {
      files.push(readEntry(repo, `profiles/${name}/${f}`, name))
    }
  }
  const problems = []
  for (const f of files) {
    if (!f.hasFrontmatter) problems.push({ file: f.rel, issue: 'no frontmatter; treated as `when: always`' })
    else if (!f.hasWhen) problems.push({ file: f.rel, issue: 'frontmatter has no `when`; treated as `always`' })
    if (!f.description) problems.push({ file: f.rel, issue: 'no `description`' })
  }
  return { files, problems }
}

function selectFiles(scan, profiles) {
  return scan.files.filter((f) => f.scope === 'global' || profiles.includes(f.scope))
}

function sourceHash(selected) {
  const hash = crypto.createHash('sha256')
  for (const f of selected) hash.update(`${f.rel}\n${f.raw}\n`)
  return hash.digest('hex').slice(0, 12)
}

const cell = (text) => String(text).replace(/\|/g, '\\|').replace(/\s*\r?\n\s*/g, ' ').trim()

function renderIndex(selected, customDir, hash) {
  const lines = [
    `<!-- excalibur:user-profile source-hash=${hash} -->`,
    '<!-- Generated by `excalibur sync` from the user profile repository. Do not edit: changes are overwritten. -->',
    '# User profile',
    '',
    "The user's own standing instructions, valid across all projects. Precedence when they conflict: the user's request in the moment, then this project's own rules, then these instructions, then Excalibur defaults.",
    '',
    'Files marked `always` are included below. For the others, open the file only when its trigger applies; skip it otherwise.',
    '',
    '## Index',
    '',
    '| File | When | Description |',
    '|---|---|---|',
    ...selected.map((f) => `| \`${customDir}/${SNAPSHOT_DIR}/${f.rel}\` | ${cell(f.always ? 'always' : f.when)} | ${cell(f.description)} |`),
  ]
  const always = selected.filter((f) => f.always && f.body)
  if (always.length) {
    lines.push('', '## Always apply')
    for (const f of always) lines.push('', `### ${f.rel}`, '', f.body)
  }
  return lines.join('\n') + '\n'
}

function git(cwd, args) {
  try {
    execFileSync('git', args, { cwd, stdio: 'pipe' })
    return true
  } catch {
    return false
  }
}

/** How git sees a path inside the project: 'tracked', 'ignored', 'untracked' or 'no-git'. */
export function gitState(cwd, rel) {
  if (!git(cwd, ['rev-parse', '--is-inside-work-tree'])) return 'no-git'
  if (git(cwd, ['ls-files', '--error-unmatch', '--', rel])) return 'tracked'
  if (git(cwd, ['check-ignore', '-q', '--', rel])) return 'ignored'
  return 'untracked'
}

function snapshotPaths(cwd) {
  const p = projectPaths(cwd)
  return {
    p,
    index: path.join(p.context, SNAPSHOT_FILE),
    dir: path.join(p.custom, SNAPSHOT_DIR),
    indexRel: `${p.customDir}/${CONTEXT_DIR}/${SNAPSHOT_FILE}`,
    dirRel: `${p.customDir}/${SNAPSHOT_DIR}/`,
  }
}

function readSnapshotHash(indexFile) {
  try {
    return fs.readFileSync(indexFile, 'utf8').match(/source-hash=([0-9a-f]+)/)?.[1] ?? null
  } catch {
    return null
  }
}

/**
 * Brings the project's snapshot in line with the user profile repository. With no
 * repository linked (or the folder gone) it does nothing and says why; the layer is
 * simply absent, never an error.
 */
export function syncUserProfile(cwd, { env = process.env, dryRun = false } = {}) {
  const s = snapshotPaths(cwd)
  if (!s.p.configured) throw new Error('No config found here. Run `npx @easy-spec/excalibur init` first.')

  const repo = getProfileRepo(env)
  if (!repo) return { status: 'no-profile' }
  if (!fs.existsSync(repo)) return { status: 'repo-missing', repo }

  const settings = getProjectSettings(cwd, env)
  const scan = scanProfile(repo)
  const known = new Set(listProfiles(repo))
  const missingProfiles = settings.profiles.filter((name) => !known.has(name))
  const selected = selectFiles(scan, settings.profiles)
  const hash = sourceHash(selected)
  const result = { status: 'synced', repo, files: selected.map((f) => f.rel), hash, missingProfiles, settings }
  if (dryRun) return { ...result, status: 'dry-run' }

  fs.rmSync(s.dir, { recursive: true, force: true })
  if (selected.length === 0) {
    fs.rmSync(s.index, { force: true })
    return { ...result, status: 'empty' }
  }

  for (const f of selected) {
    const target = path.join(s.dir, f.rel)
    ensureDir(path.dirname(target))
    fs.writeFileSync(target, f.raw, 'utf8')
  }
  ensureDir(s.p.context)
  fs.writeFileSync(s.index, renderIndex(selected, s.p.customDir, hash), 'utf8')

  // The snapshot is personal by default: keep it out of the project's git history.
  const entries = [s.indexRel, s.dirRel]
  const header = s.p.mode === 'discreet' ? 'ignored files' : 'Excalibur'
  if (settings.snapshot === 'ignored') ensureGitignore(s.p.gitignore, entries, header)
  else removeGitignoreEntries(s.p.gitignore, entries)

  touchProject(cwd, env)
  return result
}

/** Everything a status screen or `doctor` needs to know about a project's user profile layer. */
export function profileState(cwd, env = process.env) {
  const s = snapshotPaths(cwd)
  const repo = getProfileRepo(env)
  const settings = getProjectSettings(cwd, env)
  const state = {
    repo,
    repoExists: Boolean(repo && fs.existsSync(repo)),
    settings,
    available: [],
    missingProfiles: [],
    problems: [],
    snapshot: fs.existsSync(s.index) ? 'fresh' : 'none',
    git: fs.existsSync(s.index) ? gitState(cwd, s.indexRel) : 'none',
    indexRel: s.indexRel,
    warnings: [],
  }
  if (state.repoExists) {
    const scan = scanProfile(repo)
    state.available = listProfiles(repo)
    state.missingProfiles = settings.profiles.filter((name) => !state.available.includes(name))
    state.problems = scan.problems
    if (state.snapshot === 'fresh') {
      const current = sourceHash(selectFiles(scan, settings.profiles))
      if (readSnapshotHash(s.index) !== current) state.snapshot = 'stale'
    }
  }

  if (repo && !state.repoExists) state.warnings.push(`profile repository not found: ${repo}`)
  if (state.snapshot === 'stale') state.warnings.push('snapshot is older than the profile repository; run `excalibur sync`')
  if (state.snapshot === 'none' && state.repoExists) state.warnings.push('no snapshot yet; run `excalibur sync`')
  for (const name of state.missingProfiles) state.warnings.push(`profile "${name}" does not exist in the profile repository`)
  if (state.snapshot !== 'none') {
    if (settings.snapshot === 'ignored' && state.git === 'tracked') state.warnings.push('snapshot is tracked by git, but the choice is "ignored"')
    if (settings.snapshot === 'committed' && state.git === 'ignored') state.warnings.push('snapshot is ignored by git, but the choice is "committed"')
    if (s.p.mode === 'discreet' && state.git === 'tracked') state.warnings.push('discreet mode: personal instructions are tracked by git')
  }
  return state
}

/** Creates a new profile repository from the bundled template. Refuses a non-empty folder. */
export function createProfileRepo(dir) {
  const target = path.resolve(dir)
  if (!isEmptyDir(target)) throw new Error(`${target} is not empty. Pick an empty folder, or link it with \`excalibur profile link\`.`)
  copyDir(PROFILE_TEMPLATE_DIR, target)
  const created = listFiles(target)
  // Only the folder's own `.git` counts: a folder inside some other repository (even the
  // user's home directory) still needs its own.
  const initialised = fs.existsSync(path.join(target, '.git')) || git(target, ['init', '-q'])
  return { dir: target, created, git: initialised }
}

/** Creates the remote through the user's own `gh`. Private unless told otherwise. Never pushes. */
export function createRemote(dir, { name, visibility = 'private' } = {}) {
  const repoName = name ?? path.basename(path.resolve(dir))
  execFileSync('gh', ['repo', 'create', repoName, `--${visibility}`, '--source', path.resolve(dir), '--remote', 'origin'], { stdio: 'pipe' })
  return repoName
}
